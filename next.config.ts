import type { NextConfig } from "next";

const isDev = process.env.NODE_ENV !== "production";

/**
 * Conservative CSP: it does not yet nonce Next's bootstrap scripts, so inline
 * scripts are allowed. The value here is `frame-ancestors`/`object-src`/
 * `base-uri`, which stop clickjacking and injected-object tricks without
 * breaking the framework.
 */
const contentSecurityPolicy = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https:",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: contentSecurityPolicy },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=()",
  },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
];

const nextConfig: NextConfig = {
  /* config options here */
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
  // Native/binary dependencies used by document processing must stay outside
  // the bundle: @napi-rs/canvas ships a .node addon that ESM chunks can't place,
  // and bundling unpdf breaks pdf.js's Node detection so it tries to transfer
  // data to a worker ("Cannot transfer object of unsupported type").
  serverExternalPackages: ["@napi-rs/canvas", "sharp", "tesseract.js", "unpdf"],
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
